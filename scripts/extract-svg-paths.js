/**
 * Script to extract SVG path data from MiddleEarthMapSvg.tsx
 * and output it as a separate TypeScript data file for use with React Native Skia
 */

const fs = require('fs');
const path = require('path');

const inputFile = path.join(
  __dirname,
  '../src/components/MiddleEarthMapSvg.tsx',
);
const outputFile = path.join(__dirname, '../src/data/mapPathData.ts');

const content = fs.readFileSync(inputFile, 'utf-8');

// Extract path data using regex - find patterns like d="..."
// The paths are within <G id="layerName">...<AnimatedPath d="..." /></G>

const layerPatterns = [
  { id: 'legend', varName: 'LEGEND_PATH' },
  { id: 'trees', varName: 'TREES_PATH' },
  { id: 'mountains', varName: 'MOUNTAINS_PATH' },
  { id: 'coastline', varName: 'COASTLINE_PATH' },
  { id: 'water', varName: 'WATER_PATH' },
  { id: 'streets', varName: 'STREETS_PATH' },
  { id: 'titles', varName: 'TITLES_PATH' },
];

// Find each layer's path data
const extractedPaths = {};

for (const layer of layerPatterns) {
  // Pattern to find <G id="layerName">...<AnimatedPath d="..."
  const groupRegex = new RegExp(
    `<G id="${layer.id}">\\s*<AnimatedPath[^>]*d="([^"]+)"`,
    's',
  );
  const match = content.match(groupRegex);

  if (match) {
    extractedPaths[layer.varName] = match[1];
    console.log(`✓ Found ${layer.id} path (${match[1].length} chars)`);
  } else {
    console.log(`✗ Could not find ${layer.id} path`);
  }
}

// Generate the output file
let output = `// Auto-generated file - extracted from MiddleEarthMapSvg.tsx
// Generated by scripts/extract-svg-paths.js

`;

for (const [varName, pathData] of Object.entries(extractedPaths)) {
  // Escape any backticks in the path data
  const escaped = pathData.replace(/`/g, '\\`').replace(/\$/g, '\\$');
  output += `export const ${varName} = \`${escaped}\`;\n\n`;
}

// Also include the game path
const gamePathMatch = content.match(
  /const GAME_PATH\s*=\s*['"`]([^'"`]+)['"`]/,
);
if (gamePathMatch) {
  output += `export const GAME_PATH = \`${gamePathMatch[1]}\`;\n\n`;
  console.log(`✓ Found GAME_PATH (${gamePathMatch[1].length} chars)`);
}

// Add path length constant
output += `// Approximate path length for stroke-dasharray animation (in SVG units)
export const PATH_LENGTH = 3500;

// SVG viewBox dimensions  
export const SVG_WIDTH = 3059.47;
export const SVG_HEIGHT = 2350.67;
`;

fs.writeFileSync(outputFile, output);
console.log(`\n✓ Written to ${outputFile}`);
console.log(`  Total size: ${(output.length / 1024).toFixed(1)} KB`);
